// PATTERN 1: ผลรวมของช่วงตัวเลข [a, b]
// เมื่อเจอ: โจทย์ขอผลรวม/ค่าสะสมในช่วงตัวเลขต่อเนื่อง
// โค้ดนี้ทำอะไร: บวกทุกค่าตั้งแต่ a ถึง b เข้าด้วยกันแล้วพิมพ์ผลรวม
// ------------------------------------------------------------
void pattern1_rangeSum() {
    long long a, b;
    cin >> a >> b;

    long long total = 0;
    for (long long i = a; i <= b; i++) {
        total += i;
    }
    cout << total << "\n";

    // ถ้า a,b ใหญ่มาก (เป็นล้าน/พันล้าน) ลูปข้างบนจะช้าเกิน ให้ใช้สูตรแทน:
    // total = (a + b) * (b - a + 1) / 2;
}


