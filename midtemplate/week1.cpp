// PATTERN 4: สะสมค่าแบบมีเงื่อนไขพิเศษที่ตำแหน่งเฉพาะ (เช่น ทุกตัวที่ 4)
// เมื่อเจอ: วนรับค่าทีละตัว บวกสะสม แต่ "ตำแหน่งพิเศษ" มีกฎคูณ/บวกต่างจากปกติ
// โค้ดนี้ทำอะไร: เช็คตำแหน่งปัจจุบันด้วย i % N แล้วแยกกฎสองแบบ
// ------------------------------------------------------------
void pattern4_conditionalAccumulate() {
    int n;
    cin >> n;

    long long total = 0;
    for (int i = 1; i <= n; i++) {
        int val;
        cin >> val;

        if (i % 4 == 0) {        // *** เปลี่ยนเลข 4 ตามโจทย์ ***
            total += val * 2;    // *** เปลี่ยนกฎพิเศษตามโจทย์ ***
        } else {
            total += val;
        }
    }
    cout << total << "\n";

    // ระวัง: นับตำแหน่งเริ่มจาก 1 หรือ 0 ให้ตรงกับที่โจทย์อธิบายตัวอย่าง
}


// ------------------------------------------------------------
// PATTERN 5: ผลของตานี้ขึ้นกับ state จากตาก่อนหน้า (ไม่ independent ทีละตา)
// เมื่อเจอ: "ถ้าตาก่อนหน้า X แล้ว ตานี้จะ..." — ต้องจำผลตาที่แล้วไว้
// โค้ดนี้ทำอะไร: เก็บตัวแปร state ตัวเดียวแทนผลตาก่อน เช็คก่อนคำนวณตาปัจจุบัน
//              แล้วอัปเดต state ท้ายลูปทุกรอบ (ห้ามลืมอัปเดต!)
// ------------------------------------------------------------
void pattern5_statefulLoop() {
    int n;
    cin >> n;

    long long total = 0;
    int last = 0; // state: ค่าจากตาก่อนหน้า (0 = ยังไม่เต็ม/ยังไม่ overflow)

    for (int i = 1; i <= n; i++) {
        int val;
        cin >> val;

        if (last == 1000) {
            // ตาก่อนหน้า "เต็ม" -> ตานี้ไม่ได้อะไร (ตาม logic ของโจทย์ตัวอย่าง)
        } else {
            int taken = min(1000, val);
            total += taken;
        }

        // อัปเดต state ท้ายลูปเสมอ ก่อนขึ้นรอบถัดไป
        last = (last == 1000) ? 0 : min(1000, val);
    }
    cout << total << "\n";

    // *** กฎการอัปเดต state เปลี่ยนตามโจทย์แต่ละปี แต่โครงสร้าง
    //     "ตัวแปร state ตัวเดียว + เช็คก่อนใช้ + อัปเดตท้ายลูป" เหมือนเดิม ***
}


