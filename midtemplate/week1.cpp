// PATTERN 2: คำนวณสูตรต่อเนื่องหลายขั้น แล้วดึงตัวเลขหลักใดหลักหนึ่งออกมา
// เมื่อเจอ: โจทย์ให้ลำดับการคำนวณ (คูณ/หาร/บวก/ลบ) ต่อกันหลายบรรทัด
//          แล้วถามว่า "หลักที่ N ของผลลัพธ์คืออะไร"
// โค้ดนี้ทำอะไร: ทำตามสูตรทีละบรรทัดตรงๆ ด้วย long long กัน overflow
//              แล้วดึงหลักที่ต้องการด้วยการหารลอย/มอด
// ------------------------------------------------------------
void pattern2_formulaChainDigit() {
    long long n;
    cin >> n;

    long long total = n;
    total = total * 567;     // *** แก้สูตรตรงนี้ให้ตรงกับโจทย์ปีนั้นๆ ***
    total = total / 9;
    total = total + 7492;
    total = total * 235;
    total = total / 47;
    total = total - 498;

    // ดึง "หลักสิบ" ของผลลัพธ์ (ตัวอย่าง): เอาเลขมา /10 แล้ว %10
    // ถ้าโจทย์ถามหลักหน่วยก็ใช้ total % 10 เฉยๆ, หลักร้อยก็ /100 %10
    cout << abs((total / 10) % 10) << "\n";

    // ใช้ abs() เสมอเผื่อผลลัพธ์ระหว่างทางติดลบ
}


// ------------------------------------------------------------
// PATTERN 3: Josephus problem (วงกลม นับ k คนแล้วตัดออกเรื่อยๆ)
// เมื่อเจอ: คน/ของเรียงเป็นวงกลม นับไป k ตำแหน่งแล้วคัดออก ถามว่าเหลือใคร/อะไร
// โค้ดนี้ทำอะไร: จำลองการนับและตัดออกจริงๆ ด้วย vector จนเหลือ 1 ตัว
// ------------------------------------------------------------
void pattern3_josephus_small() {
    int n, k;
    cin >> n >> k;

    vector<int> people;
    for (int i = 1; i <= n; i++) people.push_back(i);

    int index = 0;
    while (people.size() > 1) {
        index = (index + k - 1) % people.size();
        people.erase(people.begin() + index);
    }
    cout << people[0] << "\n";
}

// *** ใช้อันนี้แทนถ้า n ใหญ่ (เป็นหมื่น/แสนขึ้นไป) เพราะ vector.erase ช้าเกิน ***
// สูตร Josephus มาตรฐาน O(n): หาตำแหน่งผู้ชนะแบบ 0-indexed ด้วยการไล่สะสม
void pattern3_josephus_large() {
    int n, k;
    cin >> n >> k;

    int res = 0; // 0-indexed position ของผู้ชนะ เมื่อเหลือคนเดียว
    for (int i = 2; i <= n; i++) {
        res = (res + k) % i;
    }
    cout << (res + 1) << "\n"; // แปลงกลับเป็น 1-indexed
}


