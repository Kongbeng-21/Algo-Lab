// PATTERN 6: Toggle state ทีละตัวอักษร (เจอสัญลักษณ์ -> สลับความหมาย)
// เมื่อเจอ: ต้องแปลง/แทนที่สัญลักษณ์ซ้ำๆ ที่ความหมายสลับไปมา (เปิด/ปิด, ซ้าย/ขวา)
// โค้ดนี้ทำอะไร: ใช้ boolean flag ตัวเดียว วนทีละตัวอักษรของแต่ละบรรทัด
//              เจอตัวกระตุ้น (trigger char) ก็ toggle flag แล้วเลือกพิมพ์ตาม flag
// ------------------------------------------------------------
void pattern6_toggleState() {
    string line;
    bool open = true; // flag เริ่มต้น เปิด/ปิด แล้วแต่โจทย์กำหนด

    while (getline(cin, line)) {   // ใช้ getline ไม่ใช่ cin>> เพราะมีช่องว่าง/เว้นวรรค
        for (char c : line) {
            if (c == '"') {        // *** เปลี่ยน trigger character ตามโจทย์ ***
                if (open) {
                    cout << "``";
                } else {
                    cout << "''";
                }
                open = !open;      // toggle
            } else {
                cout << c;
            }
        }
        cout << "\n";
        // ถ้าโจทย์บอกให้ reset flag ทุกบรรทัด ให้เติม: open = true; ตรงนี้
    }
}


